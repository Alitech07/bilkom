@Component({
  selector: 'app-sidebar',
  templateUrl: './sidebar.component.html',
  styleUrls: ['./sidebar.component.scss']
})
export class SidebarComponent {
  @Input() open = false;
  @Output() linkClick = new EventEmitter<void>();

  sections: SysSection[] = [];
  private _sectionModules = new Map<number, SysModule[]>();

  constructor(
    private auth: AuthService,
    private sanitizer: DomSanitizer,
  ) {
    this.buildNavTree();
  }

  private buildNavTree(): void {
    const sectionMap = new Map<number, SysSection>();
    const modulesMap = new Map<number, SysModule[]>();

    for (const m of this.auth.myModules) {
      if (!m.section || m.state !== 'ACTIVE') continue;
      if (!sectionMap.has(m.section.id)) {
        sectionMap.set(m.section.id, m.section);
        modulesMap.set(m.section.id, []);
      }
      modulesMap.get(m.section.id)!.push(m);
    }

    this.sections = [...sectionMap.values()].sort((a, b) =>
      (a.orderNum ?? 0) - (b.orderNum ?? 0)
    );
    this._sectionModules = modulesMap;
  }

  sectionModules(sectionId: number): SysModule[] {
    return this._sectionModules.get(sectionId) ?? [];
  }

  icon(name: string): SafeHtml {
    return this.sanitizer.bypassSecurityTrustHtml(ICON_MAP[name] ?? '');
  }
}
